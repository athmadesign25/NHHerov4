// Group facilities sharing a locality so the navigation lists places only.
// Shared localities open the city directory, retaining access to every facility.
export const HOSPITAL_LOCALITIES = HOSPITAL_CITIES.map(city => ({
  ...city,
  hospitals: [...new Set(city.hospitals.map(hospital => hospital.locality))].map(locality => {
    const facilities = city.hospitals.filter(hospital => hospital.locality === locality);
    return { label: locality, href: facilities.length > 1 ? city.href : facilities[0].href };
  }),
}));
